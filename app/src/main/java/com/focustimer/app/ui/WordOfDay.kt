fun wordOfTheDay(nowMillis: Long = System.currentTimeMillis()): DayWord {
    val calendar = Calendar.getInstance()
    calendar.timeInMillis = nowMillis
    calendar.set(Calendar.HOUR_OF_DAY, 0)
    calendar.set(Calendar.MINUTE, 0)
    calendar.set(Calendar.SECOND, 0)
    calendar.set(Calendar.MILLISECOND, 0)
    val dayNumber = TimeUnit.MILLISECONDS.toDays(calendar.timeInMillis)
    val index = ((dayNumber % DAY_WORDS.size) + DAY_WORDS.size) % DAY_WORDS.size
    return DAY_WORDS[index.toInt()]
}
